/** Thay đổi một field trên document đúng `documentType` trong bộ 3 giấy tờ chuẩn — dùng cho các demo case (EXPIRING_SOON/EXPIRED). */
function withDocumentOverride(
  documents: VehicleDocument[],
  documentType: VehicleDocument['documentType'],
  override: Partial<VehicleDocument>,
): VehicleDocument[] {
  return documents.map((d) => (d.documentType === documentType ? { ...d, ...override } : d))
}

